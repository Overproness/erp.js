// @ts-nocheck
const mongoose = require('mongoose');
const Schema = mongoose.Schema;

const reviewResponseSchema = new Schema({
  review: {
    type: Schema.Types.ObjectId,
    ref: 'Review',
    required: true,
  },
  business: {
    type: Schema.Types.ObjectId,
    ref: 'Business',
    required: true,
  },
  template: {
    type: Schema.Types.ObjectId,
    ref: 'ReviewTemplate',
  },
  responseText: {
    type: String,
    required: true,
    trim: true,
  },
  status: {
    type: String,
    enum: ['draft', 'pending', 'sent', 'failed'],
    default: 'draft',
  },
  isAutoGenerated: {
    type: Boolean,
    default: false,
  },
  sentAt: Date,
  platformConfirmation: {
    confirmationId: String,
    success: Boolean,
    errorMessage: String,
    responseUrl: String,
  },
  respondentName: {
    type: String,
    trim: true,
  },
  respondentTitle: {
    type: String,
    trim: true,
  },
  respondent: {
    type: Schema.Types.ObjectId,
    refPath: 'respondentModel',
  },
  respondentModel: {
    type: String,
    enum: ['CompanyOwner', 'User'],
    default: 'CompanyOwner',
  },
  revisionHistory: [{
    responseText: String,
    revisedAt: {
      type: Date,
      default: Date.now,
    },
    revisedBy: {
      type: Schema.Types.ObjectId,
      refPath: 'revisionHistory.revisedByModel',
    },
    revisedByModel: {
      type: String,
      enum: ['CompanyOwner', 'User'],
      default: 'CompanyOwner',
    },
  }],
  approvalRequired: {
    type: Boolean,
    default: false,
  },
  approvalStatus: {
    type: String,
    enum: ['not_required', 'pending', 'approved', 'rejected'],
    default: 'not_required',
  },
  approvedBy: {
    type: Schema.Types.ObjectId,
    refPath: 'approvedByModel',
  },
  approvedByModel: {
    type: String,
    enum: ['CompanyOwner', 'User'],
  },
  approvedAt: Date,
  owner: {
    type: Schema.Types.ObjectId,
    ref: 'CompanyOwner',
    required: true,
  },
  created: {
    type: Date,
    default: Date.now,
  },
  updated: {
    type: Date,
    default: Date.now,
  },
  removed: {
    type: Boolean,
    default: false,
  },
  companyID: {
    type: String,
          },
});

// Indexes
reviewResponseSchema.index({ review: 1 }, { unique: true });
reviewResponseSchema.index({ business: 1, status: 1 });
reviewResponseSchema.index({ business: 1, created: -1 });
reviewResponseSchema.index({ companyID: 1 }, { sparse: true }); // Index for companyID

// Pre-save middleware
reviewResponseSchema.pre('save', function(next) {
  this.updated = new Date();
  next();
});

// Save revision history when response text changes
reviewResponseSchema.pre('save', function(next) {
  if (this.isModified('responseText') && !this.isNew) {
    // Only push to history if not a new document and text changed
    this.revisionHistory.push({
      responseText: this.responseText,
      revisedAt: new Date(),
      revisedBy: this.respondent,
      revisedByModel: this.respondentModel
    });
  }
  next();
});

// Methods
reviewResponseSchema.methods.markAsSent = function(platformConfirmation: Record<string, any> = {}) {
  this.status = 'sent';
  this.sentAt = new Date();
  
  if (platformConfirmation) {
    this.platformConfirmation = platformConfirmation;
  }
  
  return this.save();
};

reviewResponseSchema.methods.approve = function(approverId: string, approverModel = 'CompanyOwner') {
  this.approvalStatus = 'approved';
  this.approvedBy = approverId;
  this.approvedByModel = approverModel;
  this.approvedAt = new Date();
  return this.save();
};

reviewResponseSchema.methods.reject = function() {
  this.approvalStatus = 'rejected';
  return this.save();
};

// Static methods
reviewResponseSchema.statics.findPendingApprovals = function(businessId: any) {
  return this.find({
    business: businessId,
    approvalStatus: 'pending',
    removed: false
  }).populate('review').sort({ created: -1 });
};

reviewResponseSchema.statics.getResponseRate = async function(businessId) {
  const [totalReviews, totalResponses] = await Promise.all([
    mongoose.model('Review').countDocuments({ business: businessId, removed: false }),
    this.countDocuments({ business: businessId, status: 'sent', removed: false })
  ]);
  
  if (totalReviews === 0) return 0;
  return (totalResponses / totalReviews) * 100;
};

const ReviewResponse = mongoose.model('ReviewResponse', reviewResponseSchema);
module.exports = ReviewResponse;
export {};
