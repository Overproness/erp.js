// Reputation model type definitions

export interface IReview {
  _id: string;
  business: string;
  rating: number;
  title: string;
  comment: string;
  client: { name: string; email: string; phone: string; avatarUrl: string };
  platform: 'direct' | 'google' | 'facebook' | 'yelp' | 'tripadvisor' | 'trustpilot' | 'other';
  platformReviewId: string;
  status: 'pending' | 'approved' | 'rejected' | 'flagged' | 'responded';
  sentiment: { score: number; category: string; keywords: string[] };
  source: 'web' | 'email' | 'sms' | 'api' | 'import' | 'monitoring';
  sourceLink: string;
  publishedAt: Date;
  isVerified: boolean;
  isPublic: boolean;
  hasResponse: boolean;
  metadata: { ip: string; userAgent: string; location: { city: string; region: string; country: string; coordinates: { lat: number; lng: number } } };
  owner: string;
  created: Date;
  updated: Date;
  removed: boolean;
  companyID: string;
}

export interface IReviewLink {
  _id: string;
  business: string;
  linkId: string;
  name: string;
  targetPlatform: 'direct' | 'google' | 'facebook' | 'choice';
  expiresAt: Date;
  isActive: boolean;
  customBranding: {
    enabled: boolean;
    logo: string;
    primaryColor: string;
    secondaryColor: string;
    headerText: string;
    thankYouMessage: string;
  };
  prefilledData: { clientName: string; clientEmail: string; redirectUrl: string; productName: string };
  analytics: { views: number; submissions: number; conversionRate: number; lastViewed: Date };
  settings: {
    requireEmail: boolean;
    askForContact: boolean;
    redirectAfterSubmission: boolean;
    redirectUrl: string;
    sendThankYouEmail: boolean;
    notificationEmail: string;
  };
  tags: string[];
  source: 'manual' | 'campaign' | 'integration' | 'api';
  campaignId: string;
  owner: string;
  created: Date;
  updated: Date;
  removed: boolean;
  companyID: string;
}

export interface IReviewResponse {
  _id: string;
  review: string | IReview;
  business: string;
  template: string;
  responseText: string;
  status: 'draft' | 'pending' | 'sent' | 'failed';
  isAutoGenerated: boolean;
  sentAt: Date;
  platformConfirmation: { confirmationId: string; success: boolean; errorMessage: string; responseUrl: string };
  respondentName: string;
  respondentTitle: string;
  respondent: string;
  respondentModel: string;
  revisionHistory: { responseText: string; revisedAt: Date; revisedBy: string; revisedByModel: string }[];
  approvalRequired: boolean;
  approvalStatus: 'not_required' | 'pending' | 'approved' | 'rejected';
  approvedBy: string;
  approvedByModel: string;
  approvedAt: Date;
  owner: string;
  created: Date;
  updated: Date;
  removed: boolean;
  companyID: string;
}

export interface IReviewTemplateVariable {
  name: string;
  defaultValue: string;
  description: string;
}

export interface IReviewTemplate {
  _id: string;
  business: string;
  name: string;
  description: string;
  platform: 'all' | 'direct' | 'google' | 'facebook' | 'yelp' | 'tripadvisor' | 'trustpilot';
  sentimentType: 'all' | 'positive' | 'neutral' | 'negative';
  minRating: number;
  maxRating: number;
  templateText: string;
  variables: IReviewTemplateVariable[];
  tags: string[];
  isDefault: boolean;
  useCount: number;
  category: 'general' | 'thanks' | 'apology' | 'follow-up' | 'custom';
  lastUsed: Date;
  createdBy: string;
  createdByModel: string;
  owner: string;
  created: Date;
  updated: Date;
  removed: boolean;
  companyID: string;
}
